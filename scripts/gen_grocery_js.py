"""Regenerate frontend/src/voice/groceryDictionary.js from app/core/grocery_dictionary.py.

Run from the repo root after editing the master dictionary:
    python scripts/gen_grocery_js.py
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from app.core.grocery_dictionary import ITEMS  # noqa: E402

out = ROOT / "frontend" / "src" / "voice" / "groceryDictionary.js"
aliases = {}
for item in ITEMS:
    for word in item["words"]:
        aliases[word.lower()] = item["std"]

variants = {item["std"]: list(dict.fromkeys([*item["en"], *item["std"].split()])) for item in ITEMS}

lines = [
    "// GENERATED by scripts/gen_grocery_js.py from app/core/grocery_dictionary.py — do not edit by hand.",
    "// Local grocery names (10 languages, romanised + own script) → the English name used in products.",
    "export const GENERATED_ALIASES = {",
    *(f"  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v)}," for k, v in sorted(aliases.items())),
    "}",
    "",
    "// English name → every English word that may stand for it in a product name (\"urad dal\" → udad, urid…)",
    "export const GENERATED_VARIANTS = {",
    *(f"  {json.dumps(k)}: {json.dumps(v)}," for k, v in sorted(variants.items())),
    "}",
    "",
]
out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"wrote {out.relative_to(ROOT)} — {len(aliases)} names for {len(ITEMS)} items")
